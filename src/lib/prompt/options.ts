export function byId<T extends { id: string }>(list: T[], id: string): T | undefined {
  return list.find((o) => o.id === id);
}

export function forAudience<T extends PatternOption>(list: T[], audience: Audience): T[] {
  return list.filter((o) => !o.audiences || o.audiences.includes(audience));
}

export function endingFits(ending: PatternOption, openingIds: string[]): boolean {
  if (!ending.pairsWith) return true;
  return openingIds.some((id) => ending.pairsWith!.includes(id));
}
